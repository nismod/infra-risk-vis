"""National metrics cube: the `metrics` schema from irv-metrics' SQL files

Hand-written. Creates the schema `metrics` and runs each of the installed
irv-metrics package's `irv_metrics/schema/*.sql` files, in name order, so the
tables are exactly what the package's loaders and API expect. The package's
loaders do not create or drop the schema in a database that Alembic manages
(see irv-metrics/README.md); load data with the `metrics-load` compose service.

Not autogenerated: `metrics` is in EXCLUDED_SCHEMAS in env.py. A change to the
package's SQL needs a new revision here (the files are read at upgrade time, so
editing `0001_init.sql` in place does not change an existing database).

Downgrade drops the schema and every value loaded into it.

Revision ID: 0002_metrics
Revises: 0001_baseline
Create Date: 2026-11-23 18:00:00.000000

"""
from importlib.resources import files
from typing import Sequence, Union

from alembic import op
import sqlalchemy as sa

# revision identifiers, used by Alembic.
revision: str = "0002_metrics"
down_revision: Union[str, Sequence[str], None] = "0001_baseline"
branch_labels: Union[str, Sequence[str], None] = None
depends_on: Union[str, Sequence[str], None] = None

SCHEMA = "metrics"


def schema_files():
    """The package's DDL files, in name order (`0001_init.sql`, ...)."""
    directory = files("irv_metrics").joinpath("schema")
    found = sorted(
        (f for f in directory.iterdir() if f.name.endswith(".sql")),
        key=lambda f: f.name,
    )
    if not found:
        raise RuntimeError(f"no schema/*.sql in the installed irv_metrics ({directory})")
    return found


def upgrade() -> None:
    op.execute(f"CREATE SCHEMA {SCHEMA}")
    for sql in schema_files():
        # As literal SQL: escape colons so text() takes no `:name` (e.g. in the
        # files' example queries) for a bind parameter. `%` is escaped by SQLAlchemy.
        op.execute(sa.text(sql.read_text(encoding="utf-8").replace(":", "\\:")))
    # The SQL files set search_path to metrics, public; restore the session's
    # default so later revisions (and autogenerate) see the public schema.
    op.execute("RESET search_path")


def downgrade() -> None:
    op.execute(f"DROP SCHEMA {SCHEMA} CASCADE")
